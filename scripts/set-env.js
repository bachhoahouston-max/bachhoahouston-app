// Usage: node scripts/set-env.js <staging|production>
// Copies env/<name>.json into src/config/env.js, which constant.js reads.
const fs = require('fs');
const path = require('path');

const name = process.argv[2];
const source = path.join(__dirname, '..', 'env', `${name}.json`);

if (!name || !fs.existsSync(source)) {
  console.error('Usage: node scripts/set-env.js <staging|production>');
  process.exit(1);
}

const env = JSON.parse(fs.readFileSync(source, 'utf8'));
const target = path.join(__dirname, '..', 'src', 'config', 'env.js');

fs.writeFileSync(
  target,
  `// AUTO-GENERATED by scripts/set-env.js - do not edit. Edit env/*.json instead.\n` +
    `export default ${JSON.stringify(env, null, 2)};\n`,
);
console.log(`Environment set to "${env.name}" -> ${env.baseUrl}`);
